#!/usr/bin/env python3
"""Compile the compute shaders to SPIR-V and write src/layer/shaders_spv.h.
Needs glslc (shaderc). The generated header is committed so builds do not need a shader compiler.
usage: scripts/gen-shaders.py"""
import os, struct, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src/layer/shaders")
OUT = os.path.join(ROOT, "src/layer/shaders_spv.h")

# name -> (source file, defines)
VARIANTS = {
    "bc4_unorm": ("bc45.comp", ["BLOCK_WORDS=2", "CHANNELS=1", "SNORM=0", "FMT=r8"]),
    "bc4_snorm": ("bc45.comp", ["BLOCK_WORDS=2", "CHANNELS=1", "SNORM=1", "FMT=r8_snorm"]),
    "bc5_unorm": ("bc45.comp", ["BLOCK_WORDS=4", "CHANNELS=2", "SNORM=0", "FMT=rg8"]),
    "bc5_snorm": ("bc45.comp", ["BLOCK_WORDS=4", "CHANNELS=2", "SNORM=1", "FMT=rg8_snorm"]),
}

def compile_one(src, defines):
    with tempfile.NamedTemporaryFile(suffix=".spv", delete=False) as t:
        out = t.name
    cmd = ["glslc", "--target-env=vulkan1.1", "-O", "-fshader-stage=compute"]
    cmd += ["-D" + d for d in defines] + [os.path.join(SRC, src), "-o", out]
    subprocess.run(cmd, check=True)
    data = open(out, "rb").read()
    os.unlink(out)
    assert len(data) % 4 == 0
    return struct.unpack("<%dI" % (len(data) // 4), data)

lines = ["// Generated by scripts/gen-shaders.py. Do not edit.", "#pragma once", "#include <cstdint>", "",
         "namespace exynos::spv {", ""]
for name, (src, defs) in VARIANTS.items():
    words = compile_one(src, defs)
    lines.append("// %s: %s %s" % (name, src, " ".join(defs)))
    lines.append("static const uint32_t %s[] = {" % name)
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    lines.append("};")
    lines.append("")
lines.append("}  // namespace exynos::spv")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT, "(%d variants)" % len(VARIANTS))
