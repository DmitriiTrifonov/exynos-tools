#!/usr/bin/env python3
"""Generate shader tables from third_party/bcdec/bcdec.h (MIT or Unlicense):
  src/layer/shaders/bc7_tables.glsl   BC7 partition tables
  src/layer/shaders/bc6h_tables.glsl  BC6H partition table, endpoint bit-field layouts, bit counts

Partition entries: low 2 bits = subset, bit 7 set = anchor texel of that subset (128/129/130 =
anchor of subset 0/1/2). Texels are in row-major order."""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
text = open(os.path.join(ROOT, "third_party/bcdec/bcdec.h")).read()
start = text.index("partition_sets[2][64][4][4]")
end = text.index("static int aWeight2")
body = re.sub(r"/\*.*?\*/", "", text[start:end], flags=re.S)
row = r"\{\s*\{([\d,\s]*)\},\s*\{([\d,\s]*)\},\s*\{([\d,\s]*)\},\s*\{([\d,\s]*)\}\s*\}"
entries = re.findall(row, body)
assert len(entries) == 128, len(entries)

def texels(e):
    vals = []
    for row in e:
        vals += [int(x) for x in row.split(",")]
    assert len(vals) == 16
    return vals

p2, a2_1, p3, a3_1, a3_2 = [], [], [], [], []
for n, e in enumerate(entries):
    v = texels(e)
    if n < 64:
        p2.append(sum((x & 3) << t for t, x in enumerate(v)))  # 1 bit per texel is enough, subset is 0/1
        a2_1.append(v.index(129))
    else:
        p3.append(sum((x & 3) << (2 * t) for t, x in enumerate(v)))
        a3_1.append(v.index(129))
        a3_2.append(v.index(130))

def arr(name, vals):
    rows = []
    for i in range(0, 64, 8):
        rows.append("    " + ", ".join("%du" % x for x in vals[i:i + 8]))
    return "const uint %s[64] = uint[64](\n%s\n);\n" % (name, ",\n".join(rows))

out = ["// Generated by scripts/gen-bc7-tables.py from third_party/bcdec/bcdec.h. Do not edit.",
       "// BC7_PART2: 1 bit/texel subset (2-subset). BC7_PART3: 2 bits/texel subset (3-subset).",
       "// *_ANCHOR*: texel index of the anchor (fix-up) texel of the given subset.", ""]
out.append(arr("BC7_PART2", p2))
out.append(arr("BC7_ANCHOR2_1", a2_1))
out.append(arr("BC7_PART3", p3))
out.append(arr("BC7_ANCHOR3_1", a3_1))
out.append(arr("BC7_ANCHOR3_2", a3_2))
open(os.path.join(ROOT, "src/layer/shaders/bc7_tables.glsl"), "w").write("\n".join(out))
print("wrote bc7_tables.glsl")


# ---- BC6H ---------------------------------------------------------------------------------
SIG = "(const void* compressedBlock, void* decompressedBlock, int destinationPitch, int isSigned) {"
bc6 = text[text.index("BCDECDEF void bcdec_bc6h_half" + SIG):text.index("BCDECDEF void bcdec_bc6h_float" + SIG)]
bc6 = re.sub(r"/\*.*?\*/", "", bc6, flags=re.S)

# partition table: 32 entries of 4x4
st = bc6.index("partition_sets[32][4][4]")
en = bc6.index("static int aWeight3")
rows = re.findall(r"\{\s*\{([\d,\s]*)\},\s*\{([\d,\s]*)\},\s*\{([\d,\s]*)\},\s*\{([\d,\s]*)\}\s*\}", bc6[st:en])
assert len(rows) == 32, len(rows)
p6, a6 = [], []
for e in rows:
    v = texels(e)
    p6.append(sum((x & 1) << t for t, x in enumerate(v)))
    a6.append(v.index(129))

# bits per mode: actual_bits_count[4][14]
m = re.search(r"actual_bits_count\[4\]\[14\]\s*=\s*\{(.*?)\};", bc6, flags=re.S)
rowsb = re.findall(r"\{([\d,\s]*)\}", m.group(1))
assert len(rowsb) == 4
bits = [[int(x) for x in r.split(",")] for r in rowsb]
assert all(len(r) == 14 for r in bits)

# mode bodies
cases = re.findall(r"case 0b([01]+):\s*\{(.*?)\}\s*break;", bc6, flags=re.S)
assert len(cases) == 14, len(cases)
COMP = {"r": 0, "g": 1, "b": 2}
fields_by_mode = {}
code_of_mode = {}
for code, body in cases:
    mode = int(re.search(r"mode = (\d+);", body).group(1))
    code_of_mode[mode] = int(code, 2)
    fl = []
    for line in body.split(";"):
        line = line.strip()
        if not line: continue
        a = re.match(r"([rgb])\[(\d)\] \|= bcdec__bitstream_read_bit\(&bstream\)(?: << (\d+))?$", line)
        b = re.match(r"([rgb])\[(\d)\] \|= bcdec__bitstream_read_bits\(&bstream, (\d+)\)(?: << (\d+))?$", line)
        c = re.match(r"([rgb])\[(\d)\] \|= bcdec__bitstream_read_bits_r\(&bstream, (\d+)\) << (\d+)$", line)
        d = re.match(r"partition = bcdec__bitstream_read_bits\(&bstream, 5\)$", line)
        if a:
            fl.append((COMP[a.group(1)], int(a.group(2)), 1, int(a.group(3) or 0), 0))
        elif b:
            fl.append((COMP[b.group(1)], int(b.group(2)), int(b.group(3)), int(b.group(4) or 0), 0))
        elif c:
            fl.append((COMP[c.group(1)], int(c.group(2)), int(c.group(3)), int(c.group(4)), 1))
        elif d:
            fl.append((3, 0, 5, 0, 0))
        elif line.startswith("mode ="):
            pass
        else:
            raise SystemExit("unparsed BC6H line: " + line)
    fields_by_mode[mode] = fl
assert sorted(fields_by_mode) == list(range(14))
maxf = max(len(f) for f in fields_by_mode.values())
assert maxf <= 32, maxf

def pack(f):
    comp, idx, nb, sh, rev = f
    assert nb < 16 and sh < 16
    return comp | (idx << 2) | (nb << 4) | (sh << 8) | (rev << 12)

out6 = ["// Generated by scripts/gen-bc-tables.py from third_party/bcdec/bcdec.h. Do not edit.",
        "// BC6H_FIELDS[mode*32+i]: bit-field i of the block header for the 14 modes, packed as",
        "//   comp (0 r,1 g,2 b,3 partition) | index<<2 | nbits<<4 | shift<<8 | reversed<<12",
        "// The bits are OR-ed, in stream order, into the endpoint component (shifted left by `shift`).", ""]
flat = []
for mode in range(14):
    row = [pack(f) for f in fields_by_mode[mode]]
    flat += row + [0] * (32 - len(row))
out6.append("const uint BC6H_FIELDS[14 * 32] = uint[14 * 32](")
out6.append(",\n".join("    " + ", ".join("%du" % x for x in flat[i:i + 8]) for i in range(0, len(flat), 8)))
out6.append(");\n")
out6.append("const uint BC6H_NFIELDS[14] = uint[14](" + ", ".join("%du" % len(fields_by_mode[m]) for m in range(14)) + ");\n")
codes = [255] * 32
for mode, code in code_of_mode.items():
    if mode >= 2:
        codes[code] = mode
out6.append("// 5-bit mode code (2-bit codes 0 and 1 are modes 0 and 1) -> mode, 255 = reserved")
out6.append("const uint BC6H_MODE_OF_CODE[32] = uint[32](" + ", ".join("%du" % c for c in codes) + ");\n")
for k, name in enumerate(["BC6H_BITS_W", "BC6H_BITS_DR", "BC6H_BITS_DG", "BC6H_BITS_DB"]):
    out6.append("const int %s[14] = int[14](%s);" % (name, ", ".join(str(x) for x in bits[k])))
out6.append("")
out6.append("const uint BC6H_PART[32] = uint[32](" + ", ".join("%du" % x for x in p6) + ");")
out6.append("const uint BC6H_ANCHOR[32] = uint[32](" + ", ".join("%du" % x for x in a6) + ");")
open(os.path.join(ROOT, "src/layer/shaders/bc6h_tables.glsl"), "w").write("\n".join(out6) + "\n")
print("wrote bc6h_tables.glsl")
